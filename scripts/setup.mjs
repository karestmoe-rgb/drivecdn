#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import readline from 'readline/promises';
import { stdin as input, stdout as output } from 'process';

const rootDir = process.cwd();
const envPath = path.join(rootDir, '.env');
const firebaseConfigPath = path.join(rootDir, 'firebase-applet-config.json');
const rulesPath = path.join(rootDir, 'firestore.rules');
const rulesTemplatePath = path.join(rootDir, 'preconfig', 'firestore.rules.template');

function parseDotEnv(content) {
  const result = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx === -1) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    let val = trimmed.slice(eqIdx + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    result[key] = val;
  }
  return result;
}

function escapeEnvValue(val) {
  return `"${String(val || '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

async function main() {
  console.log('\n=== DriveCDN Preconfig Setup Wizard ===');
  console.log('Cong cu nay giup ban tu dong sinh .env, firebase-applet-config.json va firestore.rules cho tai khoan cua rieng ban.\n');

  const existingEnv = fs.existsSync(envPath) ? parseDotEnv(fs.readFileSync(envPath, 'utf-8')) : {};
  let existingCfg = {};
  if (fs.existsSync(firebaseConfigPath)) {
    try {
      existingCfg = JSON.parse(fs.readFileSync(firebaseConfigPath, 'utf-8'));
    } catch {
      existingCfg = {};
    }
  }

  const rl = readline.createInterface({ input, output });
  const ask = async (label, fallback = '', required = false) => {
    const hint = fallback ? ` [${fallback}]` : '';
    while (true) {
      const answer = (await rl.question(`${label}${hint}: `)).trim();
      const resolved = answer || fallback;
      if (required && !resolved) {
        console.log('  -> Gia tri nay la bat buoc. Vui long nhap lai.');
        continue;
      }
      return resolved;
    }
  };

  try {
    console.log('--- 1. Cau hinh Firebase Web SDK (Firebase Console -> Project Settings -> Your apps) ---');
    const projectId = await ask(
      'FIREBASE_PROJECT_ID',
      existingEnv.FIREBASE_PROJECT_ID || '',
      true
    );
    const apiKey = await ask(
      'FIREBASE_API_KEY',
      existingEnv.FIREBASE_API_KEY || '',
      true
    );
    const authDomain = await ask(
      'FIREBASE_AUTH_DOMAIN',
      existingEnv.FIREBASE_AUTH_DOMAIN || `${projectId}.firebaseapp.com`,
      true
    );
    const appId = await ask(
      'FIREBASE_APP_ID',
      existingEnv.FIREBASE_APP_ID || '',
      true
    );
    const storageBucket = await ask(
      'FIREBASE_STORAGE_BUCKET (tuy chon)',
      existingEnv.FIREBASE_STORAGE_BUCKET || `${projectId}.firebasestorage.app`
    );
    const messagingSenderId = await ask(
      'FIREBASE_MESSAGING_SENDER_ID (tuy chon)',
      existingEnv.FIREBASE_MESSAGING_SENDER_ID || ''
    );
    const rawDbId = await ask(
      'FIREBASE_FIRESTORE_DATABASE_ID',
      existingEnv.FIREBASE_FIRESTORE_DATABASE_ID || '(default)'
    );
    const firestoreDatabaseId = rawDbId === 'default' || !rawDbId ? '(default)' : rawDbId;

    console.log('\n--- 2. Tai khoan Google Admin (host Google Drive & duyet User) ---');
    let adminEmail = '';
    while (true) {
      adminEmail = (
        await ask(
          'ADMIN_EMAIL (email Google quan tri)',
          existingEnv.ADMIN_EMAIL || existingCfg.adminEmail || '',
          true
        )
      ).toLowerCase();
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(adminEmail)) {
        console.log('  -> Email khong hop le. Vui long nhap dung dinh dang email.');
        continue;
      }
      break;
    }

    console.log('\n--- 3. Google Drive Host 24/7 & Upstash Redis (Co the bo trong neu chi test local) ---');
    const driveBridgeUrl = await ask(
      'DRIVE_BRIDGE_URL (URL /exec cua Apps Script, tuy chon)',
      existingEnv.DRIVE_BRIDGE_URL || ''
    );
    const driveBridgeSecret = await ask(
      'DRIVE_BRIDGE_SECRET (tuy chon)',
      existingEnv.DRIVE_BRIDGE_SECRET || ''
    );
    const driveFolderId = await ask(
      'DRIVE_FOLDER_ID (ID thu muc DriveCDN co dinh, tuy chon)',
      existingEnv.DRIVE_FOLDER_ID || ''
    );
    const kvUrl = await ask(
      'KV_REST_API_URL (Upstash Redis cho Vercel, tuy chon)',
      existingEnv.KV_REST_API_URL || ''
    );
    const kvToken = await ask(
      'KV_REST_API_TOKEN (Upstash Redis cho Vercel, tuy chon)',
      existingEnv.KV_REST_API_TOKEN || ''
    );

    const envLines = [
      '# Generated by `npm run setup`',
      `FIREBASE_API_KEY=${escapeEnvValue(apiKey)}`,
      `FIREBASE_AUTH_DOMAIN=${escapeEnvValue(authDomain)}`,
      `FIREBASE_PROJECT_ID=${escapeEnvValue(projectId)}`,
      `FIREBASE_APP_ID=${escapeEnvValue(appId)}`,
      `FIREBASE_STORAGE_BUCKET=${escapeEnvValue(storageBucket)}`,
      `FIREBASE_MESSAGING_SENDER_ID=${escapeEnvValue(messagingSenderId)}`,
      `FIREBASE_FIRESTORE_DATABASE_ID=${escapeEnvValue(firestoreDatabaseId)}`,
      '',
      `ADMIN_EMAIL=${escapeEnvValue(adminEmail)}`,
      '',
      `KV_REST_API_URL=${escapeEnvValue(kvUrl)}`,
      `KV_REST_API_TOKEN=${escapeEnvValue(kvToken)}`,
      '',
      `DRIVE_BRIDGE_URL=${escapeEnvValue(driveBridgeUrl)}`,
      `DRIVE_BRIDGE_SECRET=${escapeEnvValue(driveBridgeSecret)}`,
      `DRIVE_FOLDER_ID=${escapeEnvValue(driveFolderId)}`,
      '',
    ];
    fs.writeFileSync(envPath, envLines.join('\n'), 'utf-8');

    const clientConfig = {
      projectId,
      appId,
      apiKey,
      authDomain,
      firestoreDatabaseId,
      storageBucket,
      messagingSenderId,
      adminEmail,
    };
    fs.writeFileSync(firebaseConfigPath, `${JSON.stringify(clientConfig, null, 2)}\n`, 'utf-8');

    if (fs.existsSync(rulesTemplatePath)) {
      const tpl = fs.readFileSync(rulesTemplatePath, 'utf-8');
      const renderedRules = tpl.replaceAll('{{ADMIN_EMAIL}}', adminEmail);
      fs.writeFileSync(rulesPath, renderedRules, 'utf-8');
    }

    console.log('\n=== Hoan tat sinh file preconfig ===');
    console.log('1. Da ghi: .env');
    console.log('2. Da ghi: firebase-applet-config.json');
    if (fs.existsSync(rulesTemplatePath)) {
      console.log(`3. Da ghi: firestore.rules (da gan Admin = ${adminEmail})`);
    }
    console.log('\nCac buoc tiep theo:');
    console.log('  - Trong Firebase Console -> Authentication -> Sign-in method: Bat nha cung cap Google.');
    console.log('  - Trong Firebase Console -> Authentication -> Settings -> Authorized domains: Them ten mien app (vd: localhost, *.vercel.app).');
    console.log('  - Trong Firebase Console -> Firestore Database -> Rules: Copy noi dung file firestore.rules vua tao va bam Publish.');
    console.log('  - Chay `npm run dev` de test local hoac nap cac bien trong .env len Vercel Environment Variables va deploy.\n');
  } finally {
    rl.close();
  }
}

main().catch((err) => {
  console.error('Setup failed:', err);
  process.exit(1);
});
